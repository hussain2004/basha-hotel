
import dotenv from 'dotenv';
import Database from 'better-sqlite3';
import pg from 'pg';

dotenv.config({ path: '.env.migration', quiet: true });

const { Client } = pg;
const connectionString = process.env.DATABASE_URL;

if (!connectionString || !/^postgres(?:ql)?:\/\//i.test(connectionString)) {
  throw new Error('A valid DATABASE_URL is required in .env.migration');
}

const expectedCounts = {
  orders: 14,
  staff_users: 6,
  order_activity: 2,
};

const sqlite = new Database('basha-hotel.verified-backup.db', {
  readonly: true,
  fileMustExist: true,
});

const client = new Client({
  connectionString,
  ssl: { rejectUnauthorized: true },
});

let connected = false;
let transactionStarted = false;

const verificationQueries = {
  orders: `SELECT id, "customerName", phone, "pickupNote", items, status,
    "createdAt", "updatedAt", "trackingToken"
    FROM orders ORDER BY id`,
  staff_users: `SELECT id, username, "passwordHash", "isActive",
    "mustChangePassword", "createdAt", "updatedAt"
    FROM staff_users ORDER BY id`,
  order_activity: `SELECT id, "orderId", "actorType", "actorUsername",
    action, "createdAt"
    FROM order_activity ORDER BY id`,
};

try {
  const integrity = sqlite.pragma('integrity_check', { simple: true });

  if (integrity !== 'ok') {
    throw new Error(`SQLite integrity check failed: ${integrity}`);
  }

  const sourceCounts = {};

  for (const table of Object.keys(expectedCounts)) {
    sourceCounts[table] = sqlite
      .prepare(`SELECT COUNT(*) AS count FROM "${table}"`)
      .get().count;

    if (sourceCounts[table] !== expectedCounts[table]) {
      throw new Error(`Unexpected source count for ${table}`);
    }
  }

  const orphanedActivity = sqlite.prepare(`
    SELECT COUNT(*) AS count
    FROM order_activity a
    LEFT JOIN orders o ON o.id = a.orderId
    WHERE o.id IS NULL
  `).get().count;

  if (orphanedActivity !== 0) {
    throw new Error('Activity records reference missing orders');
  }

  const duplicateUsernames = sqlite.prepare(`
    SELECT COUNT(*) AS count
    FROM (
      SELECT LOWER(username)
      FROM staff_users
      GROUP BY LOWER(username)
      HAVING COUNT(*) > 1
    )
  `).get().count;

  if (duplicateUsernames !== 0) {
    throw new Error('Duplicate case-insensitive staff usernames found');
  }

  console.log('Source backup validated:', sourceCounts);

  await client.connect();
  connected = true;

  const existing = await client.query(`
    SELECT COUNT(*)::int AS count
    FROM information_schema.tables
    WHERE table_schema = 'public'
      AND table_type = 'BASE TABLE'
  `);

  if (existing.rows[0].count !== 0) {
    throw new Error('Destination is not empty; stopping without changes');
  }

  await client.query('BEGIN');
  transactionStarted = true;

  await client.query(`
    CREATE TABLE orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "customerName" TEXT NOT NULL,
      phone TEXT NOT NULL,
      "pickupNote" TEXT NOT NULL DEFAULT '',
      items TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      "createdAt" TEXT NOT NULL,
      "updatedAt" TEXT,
      "trackingToken" TEXT
    );

    CREATE TABLE staff_users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT NOT NULL,
      "passwordHash" TEXT NOT NULL,
      "isActive" INTEGER NOT NULL DEFAULT 1,
      "mustChangePassword" INTEGER NOT NULL DEFAULT 1,
      "createdAt" TEXT NOT NULL,
      "updatedAt" TEXT
    );

    CREATE UNIQUE INDEX staff_users_username_lower_unique
      ON staff_users (LOWER(username));

    CREATE TABLE order_activity (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "orderId" INTEGER NOT NULL REFERENCES orders(id),
      "actorType" TEXT NOT NULL,
      "actorUsername" TEXT NOT NULL,
      action TEXT NOT NULL,
      "createdAt" TEXT NOT NULL
    );
  `);

  const orders = sqlite.prepare('SELECT * FROM orders ORDER BY id').all();
  const staff = sqlite.prepare('SELECT * FROM staff_users ORDER BY id').all();
  const activity = sqlite.prepare(
    'SELECT * FROM order_activity ORDER BY id',
  ).all();

  for (const order of orders) {
    await client.query(
      `INSERT INTO orders
       (id, "customerName", phone, "pickupNote", items, status,
        "createdAt", "updatedAt", "trackingToken")
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)`,
      [
        order.id,
        order.customerName,
        order.phone,
        order.pickupNote,
        order.items,
        order.status,
        order.createdAt,
        order.updatedAt,
        order.trackingToken ?? null,
      ],
    );
  }

  for (const user of staff) {
    await client.query(
      `INSERT INTO staff_users
       (id, username, "passwordHash", "isActive",
        "mustChangePassword", "createdAt", "updatedAt")
       VALUES ($1,$2,$3,$4,$5,$6,$7)`,
      [
        user.id,
        user.username,
        user.passwordHash,
        user.isActive,
        user.mustChangePassword,
        user.createdAt,
        user.updatedAt,
      ],
    );
  }

  for (const event of activity) {
    await client.query(
      `INSERT INTO order_activity
       (id, "orderId", "actorType", "actorUsername", action, "createdAt")
       VALUES ($1,$2,$3,$4,$5,$6)`,
      [
        event.id,
        event.orderId,
        event.actorType,
        event.actorUsername,
        event.action,
        event.createdAt,
      ],
    );
  }

  for (const table of Object.keys(verificationQueries)) {
    const sourceRows = sqlite
      .prepare(`SELECT * FROM "${table}" ORDER BY id`)
      .all();

    const destinationRows = (
      await client.query(verificationQueries[table])
    ).rows;

    if (sourceRows.length !== destinationRows.length) {
      throw new Error(`Record count mismatch for ${table}`);
    }

    for (let i = 0; i < sourceRows.length; i++) {
      const source = sourceRows[i];
      const destination = destinationRows[i];

      for (const column of Object.keys(source)) {
        const sourceValue = source[column] ?? null;
        const destinationValue = destination[column] ?? null;

        if (sourceValue !== destinationValue) {
          throw new Error(
            `Verification failed: ${table}, ID ${source.id}, column ${column}`,
          );
        }
      }
    }

    console.log(
      `Verified ${table}: ${sourceRows.length} records; all fields match.`,
    );
  }

  for (const table of Object.keys(expectedCounts)) {
    const result = await client.query(
      `SELECT COALESCE(MAX(id), 0) + 1 AS next_id FROM "${table}"`,
    );

    const nextId = Number(result.rows[0].next_id);

    if (!Number.isSafeInteger(nextId) || nextId < 1) {
      throw new Error(`Invalid next ID for ${table}`);
    }

    await client.query(
      `ALTER TABLE "${table}" ALTER COLUMN id RESTART WITH ${nextId}`,
    );
  }

  await client.query('COMMIT');
  transactionStarted = false;

  console.log('Migration committed successfully.');
  console.log('All destination records and fields verified.');
} catch (error) {
  if (connected && transactionStarted) {
    await client.query('ROLLBACK').catch(() => {});
  }

  console.error('Migration stopped:', error.message);
  process.exitCode = 1;
} finally {
  sqlite.close();

  if (connected) {
    await client.end().catch(() => {});
  }
}
